/** Libellé ordinal pour affichage (1ère, 2ème, 3ème, …) */
export function getOrdinalLabel(position) {
  if (position === 1) return '1ère'
  return `${position}ème`
}

/** Libellé rôle : 1–8 = adjoints (1er adjoint … 8ème adjoint), 10 = 9ème adjoint (10ème élu), 11–29 = Nème élu */
function getRoleLabel(order) {
  if (order >= 1 && order <= 8) {
    if (order === 1) return '1er adjoint'
    return `${order}ème adjoint`
  }
  if (order === 10) return '9ème adjoint'
  if (order >= 11 && order <= 29) return `${order}ème élu`
  return `${order}ème`
}

/** Nom affiché (Prénom Nom) */
export function getDisplayName(c) {
  return c.name || '—'
}

/** Alt pour l’image : nom et rôle (adjoint / élu) */
export function getImageAlt(c) {
  const role = getRoleLabel(c.order)
  return c.name ? `${c.name}, ${role}` : `Colistier, ${role}`
}
